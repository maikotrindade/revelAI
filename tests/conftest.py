def polygon_iou(a: np.ndarray, b: np.ndarray) -> float:
    """Intersection over union of two convex quadrilaterals."""
    a32 = np.asarray(a, dtype=np.float32)
    b32 = np.asarray(b, dtype=np.float32)
    inter_area, _ = cv2.intersectConvexConvex(a32, b32)
    if inter_area <= 0:
        return 0.0
    area_a = abs(cv2.contourArea(a32))
    area_b = abs(cv2.contourArea(b32))
    union = area_a + area_b - inter_area
    return float(inter_area / union) if union > 0 else 0.0


def angle_error(a: float, b: float) -> float:
    """Smallest angular difference in degrees, modulo the 90 degree symmetry.

    A rectangle detected as w x h at theta is the same rectangle as h x w at
    theta + 90, so the comparison has to fold into a 90 degree window.
    """
    d = abs(a - b) % 90.0
    return float(min(d, 90.0 - d))


def corners_angle(corners: np.ndarray) -> float:
    """Angle of the longer axis of a quadrilateral, in degrees."""
    pts = np.asarray(corners, dtype=np.float32)
    (_, _), (_, _), angle = cv2.minAreaRect(pts)
    return float(angle)


def best_match(target: np.ndarray, candidates: list[np.ndarray]) -> tuple[int, float]:
    """Index and IoU of the candidate quadrilateral closest to ``target``."""
    if not candidates:
        return -1, 0.0
    scores = [polygon_iou(target, c) for c in candidates]
    idx = int(np.argmax(scores))
    return idx, float(scores[idx])


