_SPLIT_CACHE: dict = {}


def split_cached(image, options):
    """``split_page`` memoised across the suite.

    Detection and refinement are deterministic, so running them twice on the
    same page with the same options can only produce the same answer. Several
    tests examine different aspects of the same result and the work is by far
    the most expensive thing the suite does.
    """
    from revelai.split import split_page

    key = (id(image), tuple(sorted(vars(options).items())))
    if key not in _SPLIT_CACHE:
        _SPLIT_CACHE[key] = split_page(image, options)
    return _SPLIT_CACHE[key]


